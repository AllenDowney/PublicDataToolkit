"""Build the mental-health answer key for the full GSS (7224r3a), Task 57.

Usage: python eval/keys/full/build_gss_mental_health.py RECORDS_JSONL

The decisions are an agent's, made blind (planning/topic_annotation_design.md, "The
mental-health key: blind protocol"): a fresh subagent that saw only RECORDS_JSONL (pdt-gss
cf22b43, release 7224r3a) and the question, before any annotation existed. No person checked
them (Allen's choice). They're in gss_mental_health_decisions.yaml, as the agent wrote them.
This script checks every name against the records and writes the key in the eval's format,
as eval/keys/gss_mental_health_full.yaml.
"""

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def main():
    records = {json.loads(l)["name"] for l in Path(sys.argv[1]).read_text().splitlines() if l.strip()}
    d = yaml.safe_load((HERE / "gss_mental_health_decisions.yaml").read_text())
    hit = {x["name"]: x["why"] for x in d["hit"]}
    neutral = {x["name"]: x["why"] for x in d["neutral"]}
    assert not set(hit) & set(neutral), set(hit) & set(neutral)
    unknown = (set(hit) | set(neutral)) - records
    assert not unknown, f"not in the records: {sorted(unknown)}"
    items = ([{"dataset": "gss", "table": None, "name": n, "status": "hit", "why": w} for n, w in hit.items()]
             + [{"dataset": "gss", "table": None, "name": n, "status": "neutral", "why": w}
                for n, w in neutral.items()])
    key = {
        "question": "gss_mental_health_full",
        "expected_label": "approximate",
        "label_reason": "A topic query: no publisher subject covers it exactly, so the answer is "
                        "assembled by judgment or text search.",
        "scope": {"gss": {"release": "7224r3a", "variables": len(records),
                          "source": "pdt-gss cf22b43: metadata/releases/7224r3a, groups.jsonl"}},
        "built_by": "agent (a fresh subagent, Task 57), blind to the religion work and to annotations; "
                    "no human check. Decisions: keys/full/gss_mental_health_decisions.yaml",
        "candidate_rules": d["candidate_rules"],
        "counts": d["counts"],
        "items": items,
    }
    out = HERE.parent / "gss_mental_health_full.yaml"
    out.write_text("# Mental-health key, full GSS. Generated by full/build_gss_mental_health.py.\n"
                   + yaml.safe_dump(key, sort_keys=False, width=100))
    print(f"{out.name}: {len(hit)} hits, {len(neutral)} neutral")


if __name__ == "__main__":
    main()
