"""Build the answer keys for the Task 51 rerun, from snapshots of the dataset repos.

Usage: python eval/keys/build_task51.py SNAPSHOT_DIR

SNAPSHOT_DIR holds a copy of each repo (pdt-gss, pdt-anes-cdf, pdt-nsfg, pdt-yrbss, ...) at
the commit listed in SNAPSHOT_DIR/COMMITS (`git archive HEAD`), the same copies the runs use.
Writes, next to this script:

- religion_full.yaml: the religion question with the full GSS. The GSS part is
  full/gss_religion.yaml (build it first, from the same pdt-gss commit); the ANES CDF and NSFG
  parts are religion.yaml's, which still cover those repos (both are still slices, and their
  new variables since Task 23 aren't about religion).
- gss_ballot_a_1988_full.yaml: as gss_ballot_a_1988.yaml, over all 6,943 GSS variables.
- gss_spending_2024.yaml: every GSS variable with scale signature spending_3 (too little,
  about right, too much) and an availability entry for 2024. A structural question that isn't
  one of SKILL.md's examples. (favor_oppose, RESULTS.md's first idea, has only 2 such items.)
- catalog_sadness.yaml: which datasets ask about sadness or hopelessness, and in which years,
  across the catalog. The hand decisions are in SADNESS below.
"""

import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
AUTHOR = "Claude (PublicDataToolkit Task 51)"


def records(path):
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def commits(base):
    out = {}
    for line in (base / "COMMITS").read_text().splitlines():
        repo, rest = line.split(" ", 1)
        out[repo] = rest
    return out


def write(name, key, header):
    (HERE / name).write_text(f"# {header} Generated by build_task51.py.\n"
                             + yaml.safe_dump(key, sort_keys=False, width=100))
    hits = sum(i["status"] == "hit" for i in key["items"])
    print(f"{name}: {hits} hits, {len(key['items']) - hits} neutral")


def religion_full(base, cm):
    gss = yaml.safe_load((HERE / "full" / "gss_religion.yaml").read_text())
    slice_key = yaml.safe_load((HERE / "religion.yaml").read_text())
    want = f"pdt-gss {cm['pdt-gss']}"
    assert gss["scope"]["gss"]["source"].startswith(want), (gss["scope"], want)
    others = [i for i in slice_key["items"] if i["dataset"] != "gss"]
    return {
        "question": "religion_full",
        "expected_label": "approximate",
        "label_reason": slice_key["label_reason"],
        "scope": {"gss": gss["scope"]["gss"],
                  "anes-cdf": {**slice_key["scope"]["anes-cdf"], "commit": cm["pdt-anes-cdf"]},
                  "nsfg": {**slice_key["scope"]["nsfg"], "commit": cm["pdt-nsfg"]}},
        "built_by": "eval/keys/build_task51.py: full/gss_religion.yaml + religion.yaml (ANES CDF, NSFG)",
        "items": gss["items"] + others,
    }


def gss_ballot_a_1988_full(base, cm):
    repo = base / "pdt-gss"
    design = yaml.safe_load((repo / "dataset.yaml").read_text()).get("design", {})
    admin = {"year", "id", "ballot", *design.get("weights", []), design.get("strata"), design.get("psu")}
    items = []
    for rec in records(repo / "metadata/releases/7224r3a/variables.jsonl"):
        forms = {a.get("form") for a in rec.get("availability", []) if a["wave"] == 1988}
        if "A" in forms:
            why = "1988 form " + ",".join(sorted(f for f in forms if f))
        elif None in forms:
            why = "1988, all respondents (no form split)"
        else:
            continue
        neutral = rec["name"] in admin
        items.append({"dataset": "gss", "table": None, "name": rec["name"],
                      "status": "neutral" if neutral else "hit",
                      "why": why + ("; administrative or design" if neutral else "")})
    return {
        "question": "gss_ballot_a_1988_full",
        "expected_label": "complete",
        "label_reason": "As gss_ballot_a_1988: the `available` filter returns this set, and GSS "
                        "availability has an upstream or data origin.",
        "scope": {"gss": {"release": "7224r3a", "variables": 6943, "commit": cm["pdt-gss"]}},
        "built_by": "eval/keys/build_task51.py from pdt-gss metadata/ (same rule as build_structural.py)",
        "items": items,
    }


def gss_spending_2024(base, cm):
    repo = base / "pdt-gss"
    fo = {d["target"]["variable"] for d in records(repo / "metadata/derived/scale_signature.jsonl")
          if d["value"] == "spending_3" and d["target"].get("release", "7224r3a") == "7224r3a"}
    items = []
    for rec in records(repo / "metadata/releases/7224r3a/variables.jsonl"):
        if rec["name"] in fo and any(a["wave"] == 2024 for a in rec.get("availability", [])):
            items.append({"dataset": "gss", "table": None, "name": rec["name"], "status": "hit",
                          "why": "scale signature spending_3; availability includes 2024"})
    return {
        "question": "gss_spending_2024",
        "expected_label": "complete_by_rule",
        "label_reason": "The scale signature is a derived property (a rule), so a search by "
                        "signature and availability is complete_by_rule. Picking spending items "
                        "by reading is approximate.",
        "scope": {"gss": {"release": "7224r3a", "variables": 6943, "commit": cm["pdt-gss"]}},
        "built_by": "eval/keys/build_task51.py from pdt-gss metadata/derived/scale_signature.jsonl",
        "items": items,
    }


# Hand decisions for catalog_sadness, by Claude (PublicDataToolkit Task 51). Candidates: every
# variable in a current release of a catalog dataset whose label, description or question
# matches CANDIDATES. Rule: a hit asks whether or how often the respondent felt sad, depressed,
# down or blue, or hopeless. Neutral: on the topic but not that (diagnoses, days of poor mental
# health, help-seeking and treatment, vignettes, worthlessness, a trait self-description).
# Anything else a candidate rule caught is out (blue cards, litmus paper, Blue Cross).
CANDIDATES = re.compile(r"\bsad|hopeless|depress|\bblue\b|down.hearted|down in the dumps|worthless|"
                        r"melanchol|unhappy", re.I)
