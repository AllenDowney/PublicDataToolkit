"""Build the structural answer keys from the canonical records.

Usage: python eval/keys/build_structural.py [DATASETS_DIR]

DATASETS_DIR holds pdt-gss and pdt-anes-cdf (default: the parent of this repo).
Writes gss_ballot_a_1988.yaml and anes_therm_1978.yaml next to this script.
The keys come from metadata/, not agent/, so they test how the agent reads the
views; whether the recorded availability matches the data is C5's job.
"""

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def records(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def gss_ballot_a_1988(repo):
    """Every variable with an availability entry for 1988 on form A, or for all of 1988."""
    items = []
    for rec in records(repo / "metadata/releases/7224r3a/variables.jsonl"):
        entries = [a for a in rec["availability"] if a["wave"] == 1988]
        forms = {a.get("form") for a in entries}
        if "A" in forms:
            why = "1988 form " + ",".join(sorted(f for f in forms if f))
        elif None in forms:
            why = "1988, all respondents (no form split)"
        else:
            continue
        # Administrative variables exist for every case; listing them is neither right nor wrong.
        admin = rec["name"] in {"year", "id", "ballot", "wtssps"}
        items.append({"dataset": "gss", "table": None, "name": rec["name"],
                      "status": "neutral" if admin else "hit",
                      "why": why + ("; administrative" if admin else "")})
    return {
        "question": "gss_ballot_a_1988",
        "expected_label": "approximate",
        "label_reason": (
            "No pdt search filter or shard selects on availability, so the agent has to read "
            "waves by form from the release shard and pick variables itself. Under SKILL.md that "
            "is `approximate`, although the answer is exact. See the Task 23 findings."),
        "scope": {"gss": {"release": "7224r3a", "variables": 50}},
        "built_by": "eval/keys/build_structural.py from ../pdt-gss/metadata/",
        "items": items,
    }


def anes_therm_1978(repo):
    """Every thermometer (scale signature) with an availability entry for 1978."""
    therm = {d["target"]["variable"] for d in records(repo / "metadata/derived/scale_signature.jsonl")
             if d["property"] == "scale_signature" and d["value"] == "thermometer"}
    items, by_label = [], set()
    for rec in records(repo / "metadata/releases/20260205/variables.jsonl"):
        if (rec.get("label") or "").lower().startswith("thermometer"):
            by_label.add(rec["name"])
        if rec["name"] in therm and any(a["wave"] == 1978 for a in rec["availability"]):
            items.append({"dataset": "anes-cdf", "table": None, "name": rec["name"],
                          "status": "hit", "why": "thermometer, asked in 1978"})
    assert by_label == therm, (by_label ^ therm)   # label and scale signature agree
    return {
        "question": "anes_therm_1978",
        "expected_label": "approximate",
        "label_reason": (
            "The thermometer shard is `complete_by_rule`, but restricting it to 1978 is done by "
            "reading, which SKILL.md labels `approximate`."),
        "scope": {"anes-cdf": {"release": "20260205", "variables": 37}},
        "built_by": "eval/keys/build_structural.py from ../pdt-anes-cdf/metadata/",
        "items": items,
    }


def main():
    base = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2]
    for name, key in [("gss_ballot_a_1988", gss_ballot_a_1988(base / "pdt-gss")),
                      ("anes_therm_1978", anes_therm_1978(base / "pdt-anes-cdf"))]:
        path = HERE / f"{name}.yaml"
        header = f"# Answer key: {name}. Generated by build_structural.py; do not edit by hand.\n"
        path.write_text(header + yaml.safe_dump(key, sort_keys=False, width=100))
        hits = sum(i["status"] == "hit" for i in key["items"])
        print(f"{path.name}: {hits} hits, {len(key['items']) - hits} neutral")


if __name__ == "__main__":
    main()
