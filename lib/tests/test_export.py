def load(root, release="r1"):
    text = (root / "export" / "data-dict" / f"{release}.yaml").read_text()
    assert text.startswith("# Generated by pdt ")
    return yaml.safe_load(text)


def columns(doc, table=0):
    return {c["name"]: c for c in doc["tables"][table]["columns"]}


def test_mapping(repo_dir):
    export.build(repo_dir)
    doc = load(repo_dir)
    assert doc["$version"] == "0.1.0" and doc["name"] == "toy" and doc["label"] == "Toy Survey"
    cols = columns(doc)
    assert list(cols)[0] == "_row"
    assert cols["q1"]["type"] == "number(id)" and "1 = yes" in cols["q1"]["details"]
    assert cols["q1__code"] == {**cols["q1__code"], "type": "enum", "values": {"9": "DK [dk]"}}
    assert cols["scale"]["type"] == "number(ordinal)" and cols["scale"]["range"] == [1, 3]
    assert cols["scale__code"]["values"] == {".d": "dk [dk]"}
    assert "rule:r@1" in cols["scale__code"]["details"]
    assert "Wording 2 (waves 1991): Do you agree?" in cols["scale"]["details"]
    assert "Available: all 1990; form A 1991" in cols["scale"]["details"]
    assert cols["age"] == {**cols["age"], "type": "number(quantity)", "range": [18, 89], "units": "years"}
    assert cols["region"]["type"] == "enum" and cols["region"]["values"] == {"N": "North", "S": "South"}
    assert "type" not in cols["comment"]
    assert doc["glossary"] == {"missing type dk": export.MISSING_TYPES["dk"]}


def test_corrected_text_and_losses(tmp_path):
    root = make_repo(tmp_path)                      # q2 has a correction
    manifest = export.build(root)
    cols = columns(load(root))
    assert cols["q2"]["description"] == "And this one?"
    assert "Corrected /questions/0/text (verified): Truncated." in cols["q2"]["details"]
    losses = manifest["losses"]["r1"]
    assert losses["corrections"] == 1 and losses["groups"] == 1 and losses["variables"] == 2
    md = (root / "export" / "data-dict" / "LOSSES.md").read_text()
    assert "corrections applied" in md and "| `r1` |" in md


def test_tables_keys_and_relationships(tmp_path):
    tables = [{"id": "veh", "label": "Vehicles", "sources": ["cb"], "key": ["q1"]},
              {"id": "per", "label": "People", "sources": ["cb"], "key": ["q1", "q2"],
               "references": [{"columns": ["q1"], "table": "veh", "when": {"column": "q2", "in": [3]}}]}]
    dataset = dict(DATASET, releases=[{"id": "r1", "label": "R1", "status": "current", "sources": ["cb"],
                                       "tables": tables}])
    root = make_repo(tmp_path, dataset=dataset, variables=[], groups=[], corrections=[])
    write_jsonl(root / "metadata" / "releases" / "r1" / "veh" / "variables.jsonl", [VARIABLES[0]])
    write_jsonl(root / "metadata" / "releases" / "r1" / "per" / "variables.jsonl", VARIABLES)
    manifest = export.build(root)
    doc = load(root)
    assert [t["name"] for t in doc["tables"]] == ["veh", "per"]
    assert columns(doc, 0)["q1"]["constraints"] == ["primary_key"]
    assert columns(doc, 1)["q1"]["constraints"] == ["primary_key"]     # conditional: not a foreign key
    assert doc["relationships"] == [{"join": "per.q1 = veh.q1", "cardinality": "many-to-one",
                                     "description": "Only for rows where q2 is 3."}]
    assert manifest["losses"]["r1"]["conditional_references"] == 1


def test_is_current_and_refuses_hand_made(repo_dir):
    assert not export.is_current(repo_dir)
    export.build(repo_dir)
    assert export.is_current(repo_dir)
    write_jsonl(repo_dir / "metadata" / "groups.jsonl",
                [{"id": "g", "kind": "battery", "members": [{"name": "q1"}], "origin": PUBLISHER}])
    assert not export.is_current(repo_dir)
    other = repo_dir / "other"
    other.mkdir()
    (other / "mine.yaml").write_text("x: 1\n")
    with pytest.raises(FileExistsError):
        export.build(repo_dir, out=other)


DATA_DICT = os.environ.get("PDT_DATA_DICT") or shutil.which("data-dict")


@pytest.mark.skipif(not DATA_DICT, reason="data-dict CLI not found (set PDT_DATA_DICT)")
def test_data_dict_validates_spec_and_data(repo_dir):
    """data-dict accepts the export, and the export matches a parquet file in the common format."""
    export.build(repo_dir)
    out = repo_dir / "export" / "data-dict"
    raw = pd.DataFrame({"q1": [1, 9, 1, None], "scale": [1, 3, data.Code(".d"), 2],
                        "age": [18, 40, 89, 30], "region": ["N", "S", "N", "S"],
                        "comment": ["a", "b", None, "c"]}, dtype=object)
    table = data.split(raw, {r["name"]: r for r in RECORDS})
    table.to_parquet(out / "toy.parquet")
    doc = load(repo_dir)
    doc["tables"][0]["source"] = {"parquet": "toy.parquet"}
    (out / "r1.yaml").write_text(yaml.safe_dump(doc, sort_keys=False))
    for level in ("validate-spec", "validate-data"):
        result = subprocess.run([DATA_DICT, level, "--json", str(out / "r1.yaml")], capture_output=True, text=True)
        report = json.loads(result.stdout)
        assert report["status"] == "ok", (level, report["problems"])


