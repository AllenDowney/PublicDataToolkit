"""Tests for the human-readable site (`pdt views`, docs/)."""

import json

import pytest

from pdt import site
from test_check import DATASET, GROUPS, VARIABLES, make_repo, write_jsonl

PUBLISHER = {"origin": "publisher", "source": "cb"}


@pytest.fixture
def repo_dir(tmp_path):
    variables = [dict(VARIABLES[0], availability=[{"wave": 1985, "n": 10}, {"wave": 1987, "n": 12},
                                                  {"wave": 1988, "form": "A"}],
                      source_location={"source": "cb", "url": "https://example.org/q1"}),
                 dict(VARIABLES[1], label="<script>x</script>", availability=[{"wave": 1986}])]
    return make_repo(tmp_path, variables=variables)


def read(root, path):
    return (root / "docs" / path).read_text()


def test_build_writes_pages_with_headers(repo_dir):
    manifest = site.build(repo_dir)
    files = set(manifest["files"])
    assert {"index.html", "style.css", ".nojekyll", "search-index.js",
            "releases/r1.html", "variables/r1/q1.html", "variables/r1/q2.html",
            "groups/battery-q1.html"} <= files
    for f in files:
        if f.endswith(".html"):
            assert read(repo_dir, f).startswith(f"<!-- Generated by pdt {manifest['pdt_version']} "
                                                f"from inputs sha256:{manifest['inputs_sha256']}")


def test_variable_page(repo_dir):
    site.build(repo_dir)
    page = read(repo_dir, "variables/r1/q1.html")
    assert "Do you agree?" in page
    assert "<code>9</code>" in page and "dk" in page and "publisher:cb" in page
    assert 'href="https://example.org/q1"' in page
    assert "all 1985, 1987; form A 1988 (not 1986)" in page
    assert "not in this wave" in page                 # 1986 row: a release wave it skipped
    assert 'href="../../groups/battery-q1.html"' in page
    assert 'href="../../style.css"' in page


