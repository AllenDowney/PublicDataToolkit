    write_jsonl(root / "metadata" / "code_lists.jsonl", [lexicon])
    site.build(root)
    column = read(root, "variables/t010101.html")
    assert "Stands for" in column and "Sleeping" in column
    assert 'href="../variables/TRCODEP.html#code-010101"' in column
